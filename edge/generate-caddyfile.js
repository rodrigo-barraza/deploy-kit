// Generate edge/generated/Caddyfile from vault-service/projects.json.
//
// Every registry project with visibility:"external" and a "domain" gets a
// site block reverse-proxying to its device host + port. WebSocket upgrades
// need no configuration — Caddy forwards them natively (the failure class
// the DSM reverse proxy caused cannot occur here).
//
// TLS: with a DNS provider configured and tlsMode:"auto", every site uses
// the DNS-01 challenge (certs issue even before any public port reaches
// Caddy). tlsMode:"internal" uses Caddy's local CA for pre-cutover testing.
//
// Usage: node edge/generate-caddyfile.js  (writes edge/generated/Caddyfile)

const fs = require("fs");
const path = require("path");
const { loadProvider, providerForZone, zoneForDomain } = require("./dns/provider.js");

const EDGE_DIR = __dirname;
const ROOT_DIR = path.join(EDGE_DIR, "..", "..");
const PROJECTS_JSON = process.env.PROJECTS_JSON_PATH || path.join(ROOT_DIR, "vault-service", "projects.json");
const { loadEdgeConfig } = require("./edge-config.js");
const OUTPUT_PATH = path.join(EDGE_DIR, "generated", "Caddyfile");

function loadSites() {
  const registry = JSON.parse(fs.readFileSync(PROJECTS_JSON, "utf8"));
  const config = loadEdgeConfig();

  const deviceHosts = {};
  for (const device of registry.devices || []) {
    deviceHosts[device.id] = device.hostname;
  }
  const defaultHost = registry.defaultHost || "localhost";

  const sites = registry.projects
    .filter((project) => project.visibility === "external" && project.domain && project.port)
    .map((project) => ({
      domain: project.domain,
      upstream: `${deviceHosts[project.deployTarget || "synology"] || defaultHost}:${project.port}`,
      healthPath: project.healthPath || "/",
      source: project.id,
    }));

  for (const extra of config.extraSites || []) {
    sites.push({ domain: extra.domain, upstream: extra.upstream, healthPath: extra.healthPath || "/", source: "extraSites" });
  }

  // One domain, one owner — duplicate domains in the registry are a config bug.
  const seen = new Map();
  for (const site of sites) {
    if (seen.has(site.domain)) {
      throw new Error(
        `Duplicate domain "${site.domain}" (${seen.get(site.domain)} vs ${site.source})`,
      );
    }
    seen.set(site.domain, site.source);
  }

  return { sites, config };
}

function render(sites, config) {
  // Each site's DNS-01 challenge runs through ITS zone's provider
  // (zoneProviders override, else the default) — domains can live at
  // different registrars and every needed plugin is compiled into the image.
  const useDnsChallenge = config.tlsMode === "auto";
  const siteProviders = new Map(); // domain → provider (or null)
  const snippetProviders = new Map(); // provider.name → provider
  for (const site of sites) {
    const provider = providerForZone(zoneForDomain(site.domain, config.zoneOverrides || {}), config);
    const active = useDnsChallenge && provider.caddyPlugin ? provider : null;
    siteProviders.set(site.domain, active);
    if (active) snippetProviders.set(active.name, active);
  }

  const lines = [];
  lines.push("# GENERATED by deploy-kit/edge/generate-caddyfile.js — do not edit by hand.");
  lines.push(`# Source of truth: vault-service/projects.json + edge/edge.config.json`);
  lines.push(`# dnsProvider=${config.dnsProvider} tlsMode=${config.tlsMode} sites=${sites.length}`);
  lines.push("");
  lines.push("{");
  lines.push("\tadmin localhost:2019");
  if (config.tlsMode === "internal") lines.push("\tlocal_certs");
  lines.push("}");
  lines.push("");

  for (const provider of snippetProviders.values()) {
    lines.push(`(tls_dns_${provider.name}) {`);
    lines.push("\ttls {");
    for (const tlsLine of provider.caddyTlsLines) lines.push(`\t\t${tlsLine}`);
    lines.push("\t}");
    lines.push("}");
    lines.push("");
  }

  for (const site of sites) {
    const provider = siteProviders.get(site.domain);
    lines.push(`# ${site.source}`);
    lines.push(`${site.domain} {`);
    if (provider) lines.push(`\timport tls_dns_${provider.name}`);
    lines.push("\tencode zstd gzip");
    lines.push(`\treverse_proxy ${site.upstream}`);
    lines.push("}");
    lines.push("");
  }

  return lines.join("\n");
}

function main() {
  const { sites, config } = loadSites();
  if ((config.proxyMode || "caddy") !== "caddy") {
    console.log(
      `proxyMode is "${config.proxyMode}" — this setup keeps its own reverse proxy, ` +
        `so there is no Caddyfile to generate. (edge:dns:* and edge:preflight still apply.)`,
    );
    return;
  }
  const caddyfile = render(sites, config);
  fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
  fs.writeFileSync(OUTPUT_PATH, caddyfile);
  console.log(`✔ Wrote ${OUTPUT_PATH} — ${sites.length} sites (dnsProvider=${config.dnsProvider}, tlsMode=${config.tlsMode})`);
  for (const site of sites) {
    console.log(`  ${site.domain.padEnd(34)} → ${site.upstream}`);
  }
}

main();
